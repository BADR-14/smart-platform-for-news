import { z } from 'zod';

/** نفس قاعدة كلمة المرور في الباك-إند: 8 محارف على الأقل مع حرف ورقم. */
export const passwordSchema = z
  .string()
  .min(8, 'كلمة المرور يجب أن تكون 8 محارف على الأقل')
  .regex(/\p{L}/u, 'كلمة المرور يجب أن تحتوي على حرف واحد على الأقل')
  .regex(/\d/, 'كلمة المرور يجب أن تحتوي على رقم واحد على الأقل');
